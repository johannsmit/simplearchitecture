import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, join, sep } from 'node:path';
import type { Plugin } from 'vite';

/**
 * Writes `third-party-licenses.txt` and `web-packages.cdx.json` into the build: the licence of every
 * package that ends up in the bundle (found from the bundle's own modules, so it never goes stale), with each package's
 * licence file. elkjs (EPL-2.0) and Inter (OFL-1.1) require their notices to travel with the app.
 */

export const licensesFile = 'third-party-licenses.txt';

/**
 * The same packages as a CycloneDX list. The bundle leaves no package files for a scanner to find
 * in the image, so CI adds this list to the image's SBOM and scans it (deploy/scan-image.sh).
 */
export const webPackagesFile = 'web-packages.cdx.json';

/** Packages in the build that aren't modules of the bundle (the service worker's runtime). */
const extraPackages = [
  'workbox-core',
  'workbox-precaching',
  'workbox-routing',
  'workbox-strategies',
];

/** Where each package's source is available, for licences that ask for it (EPL-2.0). */
const sourceNotes: Record<string, string> = {
  elkjs:
    'Used unmodified, under EPL-2.0. Source code: https://github.com/kieler/elkjs (also on npm).',
};

export interface PackageInfo {
  name: string;
  version: string;
  license: string;
  text: string;
}

function packageRoot(file: string): string | undefined {
  let dir = dirname(file);
  while (dir.includes(`${sep}node_modules${sep}`)) {
    const manifest = join(dir, 'package.json');
    if (existsSync(manifest)) {
      const pkg = JSON.parse(readFileSync(manifest, 'utf8')) as { name?: unknown };
      if (typeof pkg.name === 'string') return dir;
    }
    dir = dirname(dir);
  }
  return undefined;
}

function readPackage(root: string): PackageInfo {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as Record<
    string,
    unknown
  >;
  const licenseFile = readdirSync(root).find((file) => /^(licen[cs]e|copying)(\.|$)/i.test(file));
  return {
    name: String(pkg.name),
    version: String(pkg.version),
    license: typeof pkg.license === 'string' ? pkg.license : 'see the package',
    text: licenseFile ? readFileSync(join(root, licenseFile), 'utf8').trim() : '',
  };
}

function render(packages: PackageInfo[]): string {
  const header = [
    'SimpleArchitecture: third-party software notices',
    '',
    'The web app includes the following open-source packages. Each is listed with its licence.',
    '',
  ];
  const body = packages.flatMap((pkg) => [
    '='.repeat(78),
    `${pkg.name} ${pkg.version} (${pkg.license})`,
    ...(sourceNotes[pkg.name] ? [sourceNotes[pkg.name] ?? ''] : []),
    '='.repeat(78),
    '',
    pkg.text || `Licensed under ${pkg.license}.`,
    '',
  ]);
  return [...header, ...body].join('\n');
}

/** A package URL: pkg:npm/%40scope/name@1.2.3. */
export function packageUrl(name: string, version: string): string {
  const path = name.split('/').map(encodeURIComponent).join('/');
  return `pkg:npm/${path}@${encodeURIComponent(version)}`;
}

export function webPackagesBom(
  packages: readonly Pick<PackageInfo, 'name' | 'version' | 'license'>[],
) {
  return {
    bomFormat: 'CycloneDX',
    specVersion: '1.6',
    version: 1,
    metadata: { component: { type: 'application', name: 'SimpleArchitecture web app' } },
    components: packages.map(({ name, version, license }) => ({
      type: 'library',
      'bom-ref': packageUrl(name, version),
      name,
      version,
      purl: packageUrl(name, version),
      licenses: [{ license: { name: license } }],
    })),
  };
}

export function thirdPartyLicenses(): Plugin {
  return {
    name: 'third-party-licenses',
    // The dev server has no bundle to read, so it says where the notices come from.
    configureServer(server) {
      server.middlewares.use(`/${licensesFile}`, (_request, response) => {
        response.setHeader('Content-Type', 'text/plain; charset=utf-8');
        response.end(
          'Third-party notices are generated by the production build (npm run build).\n',
        );
      });
    },
    generateBundle() {
      const roots = new Set<string>();
      for (const id of this.getModuleIds()) {
        const file = id.split('?')[0] ?? '';
        if (!file.includes(`${sep}node_modules${sep}`)) continue;
        const root = packageRoot(file);
        if (root) roots.add(root);
      }
      for (const name of extraPackages) {
        const candidate = join(process.cwd(), '..', 'node_modules', name);
        if (existsSync(join(candidate, 'package.json'))) roots.add(candidate);
      }
      const packages = [...roots].map(readPackage).sort((a, b) => a.name.localeCompare(b.name));
      this.emitFile({ type: 'asset', fileName: licensesFile, source: render(packages) });
      this.emitFile({
        type: 'asset',
        fileName: webPackagesFile,
        source: `${JSON.stringify(webPackagesBom(packages), null, 2)}\n`,
      });
    },
  };
}
